def _m(values: list[float]) -> float:
    return mean_std(values)[0]


def _img(figs: dict[str, Path], key: str, alt: str) -> list[str]:
    return [f"![{alt}](plots/{figs[key].name})", ""] if key in figs else []


def _typology_drops(res: dict[str, Any], scenario: str) -> list[tuple[str, float, float]]:
    """Typologies ordered by how much recall is lost from the centralised MLP to FedAvg."""
    out = []
    for t in TYPOLOGIES:
        central = [res["baselines"][s]["methods"]["mlp"]["recall_by_typology"][t] for s in res["seeds"] if res["baselines"][s]]
        fed = [f["recall_by_typology"][t] for f in (fl_final(res, s, scenario, "fedavg") for s in res["seeds"]) if f is not None]
        central, fed = [v for v in central if v is not None], [v for v in fed if v is not None]
        if central and fed:
            out.append((t, float(np.mean(central)), float(np.mean(fed))))
    return sorted(out, key=lambda x: x[2] - x[1])


def build_results(cfg: Config) -> Path:
    """Write tables, figures and RESULTS.md; returns the path of the report."""
    res = load_results(cfg)
    root = cfg.path("results_dir")
    plots_dir, tables_dir = root / "plots", root / "tables"
    seeds = res["seeds"]
    names = scenario_by_name(cfg)
    primary = primary_scenario(cfg).name
    counts = [int(n) for n in cfg.fl.experiments.n_clients]
    base = counts[0]
    iid = f"n{base}_iid"
    alphas = sorted([float(a) for a in cfg.fl.experiments.alphas])
    strong = f"n{base}_dir{alphas[0]:g}"

    figs = {**make_figures(res, cfg, plots_dir), **make_ledger_figures(res, plots_dir), **make_scoring_figures(res, plots_dir), **make_stretch_figures(res, plots_dir)}
    have_base = all(res["baselines"][s] for s in seeds)
    have_fl = all(res["fl"][s].get(iid, {}).get("fedavg") for s in seeds)
    L: list[str] = []

    def add(*lines: str) -> None:
        L.extend(lines)

    add("# Results", "",
        "Generated by `scripts/evaluate.py` from the files in `results/`. Every number below is read from a result file; tables are also",
        "written as CSV to `results/tables/`.", "",
        "> **All data is synthetic.** These results show how the methods compare under the assumptions of the simulator",
        "> (`docs/data_generator.md`). They are not estimates of detection performance on real trade data, and nothing here is a",
        "> determination that a trade is laundering: the system flags trades for human review.", "")

    # ------------------------------------------------------------------ 1. summary
    add("## 1. Summary", "",
        "**Research question.** Can Federated Learning and Blockchain support privacy-preserving TBML detection across multiple organisations?", "",
        f"**Short answer.** Yes, with limits. Mean of {len(seeds)} seeds, test period:", "")
    if have_base:
        rules, lgbm, mlp = _m(baseline_values(res, "rules")), _m(baseline_values(res, "lightgbm")), _m(baseline_values(res, "mlp"))
        add(f"1. **Learning beats rules.** The rules engine reaches F1 {rules:.3f}; pooled-data models reach {mlp:.3f} (MLP) and {lgbm:.3f} (LightGBM).")
    if have_base and have_fl:
        fed, local, pooled = _m(fl_values(res, iid, "fedavg")), _m(fl_values(res, iid, "local")), _m(fl_values(res, iid, "pooled_local_features"))
        add(f"2. **Federated learning works without moving raw data.** With {base} institutions and an IID split, FedAvg reaches F1 {fed:.3f}, against "
            f"{local:.3f} when each institution trains alone ({fed - local:+.3f}). The server received model parameters and fixed-size aggregates only, "
            "which is enforced and tested.")
        add(f"3. **Parameter averaging costs almost nothing; fragmentation costs a lot.** One model trained on the pooled rows, but with each institution's "
            f"locally computed indicators, reaches {pooled:.3f}, the same level as FedAvg. Both are below the centralised MLP ({mlp:.3f}), because indicators that "
            "need to see related trades together (trade graph, shared bills of lading, entity history) are computed from one institution's records only.")
        drops = _typology_drops(res, iid)[:2]
        if drops:
            add("   The typologies that lose most recall from centralised to federated are "
                + " and ".join(f"{t.replace('_', ' ')} ({c:.2f} to {f:.2f})" for t, c, f in drops) + ".")
        gains = [(n, _m(fl_values(res, f"n{n}_iid", "fedavg")) - _m(fl_values(res, f"n{n}_iid", "local"))) for n in counts if fl_values(res, f"n{n}_iid", "fedavg")]
        add("4. **The thinner the data is spread, the more federating helps:** " + ", ".join(f"{g:+.3f} F1 at {n} clients" for n, g in gains) + " (IID).")
        if fl_values(res, strong, "fedavg"):
            s_local, s_fed, s_tuned = _m(fl_values(res, strong, "local")), _m(fl_values(res, strong, "fedavg")), _m(fl_values(res, strong, "fedavg_finetuned"))
            tuned = f" Fine-tuning the global model locally closes the gap ({s_tuned:.3f})." if not np.isnan(s_tuned) else ""
            add(f"5. **Under strong skew, local models win.** At Dirichlet α = {alphas[0]:g}, local-only reaches {s_local:.3f} and FedAvg {s_fed:.3f}: when a "
                f"typology concentrates at one institution, its own graph is intact and its own threshold fits its own positive rate.{tuned}")
        comm = [res["fl"][s][iid]["fedavg"]["communication"] for s in seeds]
        add(f"6. **Communication is small.** A model is {mb(comm[0]['model_bytes'])}; a 30-round run with {base} clients moves "
            f"{mb(np.mean([c['total_bytes'] for c in comm]))} in total and reaches 95% of its final F1 after about "
            f"{np.mean([c['convergence']['rounds'] for c in comm]):.0f} rounds.")
    bench = res["ledger"]["benchmark"]
    if bench:
        backend = "evm" if "evm" in bench else "python"
        b = bench[backend]
        add(f"7. **The evidence ledger is cheap enough to run alongside.** On the {backend.upper() if backend == 'evm' else 'pure-Python'} backend a registration takes "
            f"{b['single']['latency']['p50_ms']:.1f} ms (p50) / {b['single']['latency']['p95_ms']:.1f} ms (p95) and {b['single']['cost_per_record']:,.0f} "
            f"{b['cost_unit']}; Merkle batching brings a trade document down to {b['merkle']['cost_per_record']:,.0f} {b['cost_unit']}. Tampering with an invoice, "
            "a model update or an alert is detected.")
    if res["alerts"]:
        ev = res["alerts"]["evaluation"]
        crit, high, med = ev["bands"][3], ev["bands"][2], ev["bands"][1]
        add(f"8. **Alerts are explainable and calibrated.** Precision is {100 * (med['precision'] or 0):.0f}% / {100 * (high['precision'] or 0):.0f}% / "
            f"{100 * (crit['precision'] or 0):.0f}% in the Medium / High / Critical bands, and the suspected typology is right for "
            f"{100 * ev['typology_attribution']['top1_accuracy']:.0f}% of alerts on illicit trades.")
    add("", "What this does not show: performance on real data, robustness against adaptive launderers, or behaviour of a real multi-node chain. See section 11.", "")

    # ------------------------------------------------------------------ 2. setup
    add("## 2. Setup", "")
    rows = []
    for s in seeds:
        d, f = res["data"][s], res["features"][s]
        if d and f:
            sp = f["split"]
            rows.append([s, f"{d['n_trades']:,}", f"{d['n_illicit']:,} ({100 * d['illicit_rate']:.2f}%)", f"{d['n_entities']:,}",
                         *[f"{sp[k]['n']:,} ({100 * sp[k]['illicit_rate']:.1f}%)" for k in ("train", "val", "test")]])
    if rows:
        add(md_table(["Seed", "Trades", "Illicit", "Entities", "Train (illicit)", "Validation (illicit)", "Test (illicit)"], rows, "lrrrrrr"), "")
    add("- **Split.** By invoice date: oldest 60% of the period for training, next 20% for validation, newest 20% for testing.",
        "- **Threshold.** Every method's decision threshold maximises F1 on validation; test data never influences it.",
        "- **Metrics.** Precision, recall, F1, PR-AUC (average precision), ROC-AUC, false-positive rate (FPR), confusion matrix, recall per typology.",
        "  All methods are scored by the same histogram-based code, which is what a federation can compute without pooling predictions.",
        f"- **Seeds.** A seed fixes the data, the client split and the model initialisation. Tables give mean ± standard deviation over {len(seeds)} seeds.",
        "- **Local-only and fine-tuned models** use one threshold per client; their PR-AUC and ROC-AUC are for the merged ranking of all clients' scores.", "")

    # ------------------------------------------------------------------ 3. objective 1
    add("## 3. Objective 1: risk indicators", "",
        f"{len(FEATURES)} indicators from invoice, shipment, payment and counterparty data (`docs/features.md`): "
        + ", ".join(f"{sum(f.group == g for f in FEATURES)} {g}" for g in GROUPS) + ".", "")
    report = res["features"].get(seeds[0])
    if report:
        rows = []
        for t, info in report["typologies"].items():
            top = info.get("top_targeted") or info["top_features"]
            rows.append([t.replace("_", " "), f"`{top[0]['feature']}`", f"{top[0]['separation']:.3f}", ", ".join(f"`{x['feature']}` ({x['separation']:.2f})" for x in top[1:3])])
        add("Does each typology have an indicator that responds to it? The table lists, among the indicators designed for a typology (feature dictionary),",
            "the ones that separate it best from legitimate trades: one-dimensional ROC-AUC of the single indicator, folded so that 0.5 is no signal and",
            f"1.0 is perfect, on the training period of seed {seeds[0]}.", "",
            md_table(["Typology", "Strongest indicator", "Separation", "Next two"], rows, "llrl"), "",
            "A high separation does not mean high precision: most indicators are zero for almost all legitimate trades, and the few legitimate",
            "trades that do trigger them still outnumber the illicit ones.", "")
        write_csv(tables_dir / "indicators_by_typology.csv", ["typology", "strongest_indicator", "separation", "next_two"], rows)

    # ------------------------------------------------------------------ 4. objective 2
    add("## 4. Objective 2: baselines (rules engine and centralised ML)", "", *_img(figs, "methods", "F1 by method"))
    key_scenarios = [x for x in [iid, primary, strong] if x in names]
    key_scenarios = list(dict.fromkeys(key_scenarios))
    header, det_rows, confusion = table_detection(res, cfg, key_scenarios)
    central_rows = [r for r in det_rows if r[1] == "pooled"]
    if central_rows:
        add("Pooled data, one party holds everything (the upper bound for a federation):", "", md_table([header[0], *header[2:]], [[r[0], *r[2:]] for r in central_rows]), "")
    write_csv(tables_dir / "detection_performance.csv", header, det_rows)
    if have_base:
        per_rule = res["baselines"][seeds[0]]["methods"]["rules"]["per_rule"]
        rule_name = {r.rule_id: r for r in RULES}
        rows = [[r["rule"], rule_name[r["rule"]].name, r["typology"].replace("_", " "), r["hits"], "-" if r["precision"] is None else f"{100 * r['precision']:.0f}%",
                 "-" if r["recall_own_typology"] is None else f"{100 * r['recall_own_typology']:.0f}%"] for r in per_rule]
        any_rule = res["baselines"][seeds[0]]["methods"]["rules"]["any_rule"]
        add(f"Rule book on the test period of seed {seeds[0]} (pooled view). *Precision*: share of hits that are illicit. *Recall*: share of the rule's own",
            "typology that it catches.", "", md_table(["Rule", "Red flag", "Typology", "Hits", "Precision", "Recall"], rows, "lllrrr"), "",
            f"At least one rule fires on {100 * any_rule['alert_rate']:.1f}% of trades; that set contains {100 * any_rule['recall']:.0f}% of the illicit trades at "
            f"{100 * any_rule['precision']:.0f}% precision. Rules find most cases but bury them in false alerts.", "")
        write_csv(tables_dir / "rules.csv", ["rule", "red_flag", "typology", "hits", "precision", "recall_own_typology"], rows)

    # ------------------------------------------------------------------ 5. objective 3
    add("## 5. Objective 3: federated learning", "")
    if have_fl:
        add("Horizontal FL with FedAvg on Flower. Each client is an institution that holds the complete linked records of its own trades and computes",
            "its indicators from those records only (`docs/fl_design.md`).", "", "### 5.1 Does federating help?", "", *_img(figs, "dumbbell", "Local-only against FedAvg"))
        s_header, s_rows = table_scenarios(res, cfg)
        add(md_table(s_header, s_rows, "lrrr" + "r" * (len(s_header) - 4)), "",
            "F1, mean ± std. *Pooled model on local features* is a diagnostic, not a deployable method: it pools rows but uses each client's locally",
            "computed indicators, so the gap from the centralised MLP to it is what information fragmentation costs, and the gap from it to FedAvg is",
            "what training by parameter averaging costs. *Client thresholds*: same global model, each client picks its own threshold.",
            "*Local fine-tuning*: each client adapts the global model to its own data after training, without sending anything.", "")
        write_csv(tables_dir / "fl_scenarios.csv", s_header, s_rows)
        fed_rows = [r for r in det_rows if r[1] != "pooled"]
        add("### 5.2 Detection metrics of the federated and local methods", "", md_table(header, fed_rows, "ll" + "r" * 6), "")
        add("### 5.3 F1 by round", "", *_img(figs, "rounds", "F1 by round"))
        add("### 5.4 F1 against data skew (Dirichlet α)", "", *_img(figs, "alpha", "F1 against Dirichlet alpha"))
        prox = [(a, _m(fl_values(res, f"n{base}_dir{a:g}", "fedavg")), _m(fl_values(res, f"n{base}_dir{a:g}", "fedprox"))) for a in alphas]
        diffs = [p - f for _, f, p in prox]
        verdict = ("FedProx does not improve on FedAvg at any α" if max(diffs) <= 0.005 else "FedProx is ahead at some α and behind at others")
        add("FedProx (μ = " + f"{float(cfg.fl.proximal_mu):g}) against FedAvg: " + "; ".join(f"α = {a:g}: {p:.3f} vs {f:.3f}" for a, f, p in prox)
            + f". {verdict}: the differences range from {min(diffs):+.3f} to {max(diffs):+.3f} F1, small against the spread between seeds.", "")
        add("### 5.5 F1 against the number of clients", "", *_img(figs, "clients", "F1 against number of clients"))
        add("### 5.6 Which laundering patterns each method catches", "", *_img(figs, "typology", "Recall per typology"))
        t_header, t_rows, _, _ = table_typology(res, cfg, iid)
        add(f"Recall per typology, {names[iid].label}, mean of {len(seeds)} seeds:", "", md_table(t_header, t_rows), "")
        write_csv(tables_dir / "recall_by_typology.csv", t_header, t_rows)
        run = res["primary"] or res["fl"][seeds[0]][iid]["fedavg"]
        b = run["boundary"]
        add("### 5.7 Raw data stays local", "",
            f"Every reply that reached the server in the primary run was checked against a whitelist before use: {b['replies_checked']} replies "
            f"({b['kinds']['stats']} feature-statistics, {b['kinds']['train']} training, {b['kinds']['evaluate']} evaluation), {b['violations']} violations, "
            f"{b['array_records_outside_training']} arrays outside training replies. The largest training reply was {mb(b['max_reply_bytes']['train'])} "
            f"for a {mb(run['communication']['model_bytes'])} model: its size is fixed by the model, not by the client's data. Twelve ways of smuggling rows "
            "into a reply are rejected in `tests/test_fl.py`.", "")
    else:
        add("_Federated results are missing; run `scripts/run_fl_experiments.py`._", "")

    # ------------------------------------------------------------------ 6. communication
    add("## 6. Communication overhead", "")
    if have_fl:
        c_header, c_rows = table_communication(res, cfg)
        add(*_img(figs, "communication", "F1 against traffic"), md_table(c_header, c_rows, "r" + "r" * (len(c_header) - 1)), "",
            "Bytes are the serialised (protobuf) size of every message. An evaluation reply carries two score histograms, not predictions.",
            f"The 90% target is {float(cfg.fl.target_f1_frac):.2f} x the centralised MLP's F1 for the same seed.", "")
        write_csv(tables_dir / "communication.csv", c_header, c_rows)

    # ------------------------------------------------------------------ 7. objective 4
    add("## 7. Objective 4: blockchain evidence layer", "")
    if bench:
        reg, tamper = res["ledger"]["registration"], res["ledger"]["tamper_demo"]
        backends = [k for k in ("evm", "python") if k in bench]
        label = {"evm": "EVM (Hardhat node)", "python": "Pure Python"}

        def row(name: str, fn) -> list[Any]:
            return [name, *[fn(bench[k]) for k in backends]]

        rows = [
            row("Single registration, latency p50 / p95", lambda b: f"{b['single']['latency']['p50_ms']:.1f} / {b['single']['latency']['p95_ms']:.1f} ms"),
            row("Single registration, throughput", lambda b: f"{b['single']['records_per_second']:,.0f} records/s"),
            row("Cost per record, single", lambda b: f"{b['single']['cost_per_record']:,.0f} {b['cost_unit']}"),
            *[row(f"Batch of {size}: throughput", lambda b, size=size: next((f"{r['records_per_second']:,.0f} records/s" for r in b["batched"] if r["batch_size"] == size), "-"))
              for size in sorted({r["batch_size"] for r in bench[backends[0]]["batched"] if r["batch_size"] > 1})],
            row("Cost per record in the largest batch", lambda b: f"{b['batched'][-1]['cost_per_record']:,.0f} {b['cost_unit']}"),
            row("Merkle root per batch of documents: throughput", lambda b: f"{b['merkle']['records_per_second']:,.0f} documents/s"),
            row("Cost per document with Merkle batching", lambda b: f"{b['merkle']['cost_per_record']:,.1f} {b['cost_unit']}"),
            row("Ledger storage per record", lambda b: f"{b['storage_bytes_per_record']:.0f} bytes"),
            row("Ledger storage per document with Merkle batching", lambda b: f"{b['merkle']['storage_bytes_per_record']:.2f} bytes"),
            row("Read (`verify`) latency p50", lambda b: f"{b['verify']['p50_ms']:.2f} ms" if b["verify"]["p50_ms"] >= 0.01 else "< 0.01 ms"),
        ]
        add(md_table(["Measure", *[label[k] for k in backends]], rows, "l" + "r" * len(backends)), "")
        write_csv(tables_dir / "ledger_benchmark.csv", ["measure", *backends], rows)
        if "evm" in bench and "block_interval" in bench["evm"]:
            bi = bench["evm"]["block_interval"]
            add(f"With blocks mined every {bi['block_interval_s']:g} s (how a real permissioned chain behaves) one registration takes "
                f"{bi['sequential_latency']['p50_ms'] / 1000:.1f} s, and {bi['concurrent']['records']} registrations submitted together are all final after "
                f"{bi['concurrent']['seconds_until_all_final']:.1f} s in {bi['concurrent']['blocks_used']} block{'s' if bi['concurrent']['blocks_used'] != 1 else ''}. "
                "Latency is then set by the block interval, not by the contract.", "")
        add(*_img(figs, "ledger_modes", "Throughput and gas by write mode"), *_img(figs, "storage", "On-chain storage growth"))
        if "storage" in figs:
            add("The storage lines are the measured bytes per record (contract storage slots; state-trie overhead excluded) multiplied by the number of documents.", "")
        totals = []
        if reg:
            totals.append(["Trade documents at ingestion", f"{reg['documents']:,} documents in {reg['batches']:,} Merkle batches", f"{reg['hash_seconds'] + reg['ledger_seconds']:.1f} s",
                           f"{reg['cost_per_document']:,.0f} {reg['cost_unit']} per document"])
        if res["primary"] and res["primary"].get("ledger"):
            led = res["primary"]["ledger"]
            totals.append(["Model hashes of the primary FL run", f"{led['client_updates']} client updates + {led['global_models']} global models",
                           f"{led['latency_ms_p50']:.0f} ms p50 each", f"{led['cost_mean']:,.0f} {led['cost_unit']} each"])
        if res["alerts"] and res["alerts"]["ledger"].get("alerts_registered"):
            led = res["alerts"]["ledger"]
            totals.append(["Alerts", f"{led['alerts_registered']} alerts", f"{led['latency_ms_p50']:.0f} ms p50 each", f"{led['cost_mean']:,.0f} {led['cost_unit']} each"])
        if totals:
            add("What the pipeline registered (primary seed):", "", md_table(["Evidence", "Volume", "Time", "Cost"], totals, "llrr"), "")
        if tamper:
            doc = tamper["trade_document"]
            rows = [["Invoice as registered", "verified" if doc["original"]["verified"] else "REJECTED"],
                    [f"Invoice value changed from {doc['original_value']:,.2f} to {doc['tampered_value']:,.2f}", "rejected" if not doc["tampered"]["verified"] else "VERIFIED"],
                    ["Same, and the off-chain index rewritten to match", "rejected" if not doc["tampered_with_index_rewritten"]["verified"] else "VERIFIED"]]
            if tamper.get("model_update"):
                m = tamper["model_update"]
                rows += [[f"Global model of round {m['round']}", "verified" if m["original"]["on_ledger"] else "REJECTED"],
                         ["One weight changed by 0.001", "rejected" if not m["one_weight_changed"]["on_ledger"] else "VERIFIED"]]
            if tamper.get("alert"):
                a = tamper["alert"]
                rows += [["Alert as raised", "verified" if a["original"]["on_ledger"] else "REJECTED"],
                         ["Alert with its score lowered afterwards", "rejected" if not a["score_lowered"]["on_ledger"] else "VERIFIED"]]
            add(f"Integrity verification demo (`scripts/ledger_tamper_demo.py`, {tamper['backend']} backend):", "", md_table(["Case", "Result"], rows, "ll"), "")
        add("Only hashes, document types, opaque reference ids and timestamps are on the ledger. Design and limitations: `docs/ledger.md`.", "")
    else:
        add("_Ledger results are missing; run `scripts/ledger_register.py` and `scripts/ledger_benchmark.py`._", "")

    # ------------------------------------------------------------------ 8. objective 5
    add("## 8. Objective 5: explainable risk scores", "")
    if res["alerts"]:
        ev = res["alerts"]["evaluation"]
        limits = res["alerts"]["scorer"]["bands"]
        ranges = {"Low": f"0 - {limits['medium']:.0f}", "Medium": f"{limits['medium']:.0f} - {limits['high']:.0f}", "High": f"{limits['high']:.0f} - {limits['critical']:.0f}",
                  "Critical": f"{limits['critical']:.0f} - 100"}
        rows = [[b["band"], ranges[b["band"]], f"{b['trades']:,}", f"{b['illicit']:,}", "-" if b["precision"] is None else f"{100 * b['precision']:.1f}%",
                 f"{100 * b['share_of_all_illicit']:.1f}%"] for b in ev["bands"]]
        add(f"`risk = 100 x C({ev['model_weight']:g} x P_model + {1 - ev['model_weight']:g} x P_rules)`, every part calibrated on validation histograms "
            "(`docs/scoring.md`). Primary run, test period:", "", *_img(figs, "bands", "Risk bands and calibration"),
            md_table(["Band", "Score", "Trades", "Illicit", "Precision", "Share of all illicit trades"], rows, "llrrrr"), "")
        write_csv(tables_dir / "risk_bands.csv", ["band", "score", "trades", "illicit", "precision", "share_of_all_illicit"], rows)
        comp = ev["comparison"]
        rows = [[label, *[f"{comp[k][m]:.3f}" for m in ("f1", "precision", "recall", "pr_auc")], f"{100 * comp[k]['fpr']:.2f}%"]
                for k, label in [("risk_score", "Risk score (blend)"), ("model_only", "Global model alone"), ("rules_only", "Rules alone (local indicators)")]]
        cal = ev["calibration"]
        ta = ev["typology_attribution"]
        add(md_table(["Score", "F1", "Precision", "Recall", "PR-AUC", "FPR"], rows), "",
            f"- **Calibration.** Expected calibration error {cal['model_raw']['ece']:.4f} for the model as trained, {cal['risk_score']['ece']:.4f} for the risk score; "
            f"Brier score {cal['model_raw']['brier']:.4f} against {cal['risk_score']['brier']:.4f}.",
            f"- **Blend weight.** Fixed at {ev['model_weight']:g} in advance; the best value on validation is {ev['best_weight_on_validation']:g}. "
            "The sweep is in `docs/scoring.md`.",
            f"- **Alerts.** {ev['alerts']['total']} alerts, {100 * ev['alerts']['precision']:.0f}% on truly illicit trades. Each lists its top SHAP contributions in plain "
            "English, the rules that fired, a suspected typology, and its hash and transaction id. A readable sample is in `results/alerts/report.md`.",
            f"- **Suspected typology** is right for {100 * ta['top1_accuracy']:.0f}% of alerts on illicit trades and within the top two for {100 * ta['top2_accuracy']:.0f}%.",
            f"- **Rule floor.** {ev['rule_floor']['alerts_raised_by_floor']} alert(s) were raised only because of the rule floor; "
            f"{ev['rule_floor']['of_which_illicit']} of them on illicit trades.",
            f"- **SHAP.** Method: {', '.join(sorted(set(res['alerts']['shap']['method'])))}; additivity error {res['alerts']['shap']['additivity_error']:.1e}.", "")
    else:
        add("_Alert results are missing; run `scripts/generate_alerts.py`._", "")

    # ------------------------------------------------------------------ 9. stretch
    add("## 9. Stretch goals", "")
    st = res["stretch"]
    if st["secagg"]:
        s = st["secagg"]
        add("### 9.1 Secure aggregation (pairwise additive masking)", "",
            f"Clients send their weighted updates as fixed-point 64-bit integers with pairwise masks that cancel in the sum. After one round the aggregated "
            f"model differs from plain FedAvg by at most {s['one_round']['max_abs_weight_difference']:.1e} per weight, with "
            f"{'the same' if s['one_round']['same_confusion_matrix'] else 'a different'} confusion matrix. Over the full run rounding differences are amplified by "
            f"training: F1 {s['secure']['f1']:.3f} against {s['plain']['f1']:.3f}. The upload is {s['upload_overhead_factor']:.2f}x larger. "
            "The server sees only masked arrays. Not handled: a client that drops out mid-round (the masks then do not cancel).", "")
    if st["dp"]:
        d = st["dp"]
        rows = [["no DP", "-", pm([r["f1"] for r in d["non_private"]]), pm([r["pr_auc"] for r in d["non_private"]])]]
        rows += [[f"ε = {row['epsilon']:g}", f"{np.mean([np.mean(r['noise_multipliers']) for r in row['runs']]):.2f}", pm([r["f1"] for r in row["runs"]]),
                  pm([r["pr_auc"] for r in row["runs"]])] for row in sorted(d["private"], key=lambda x: -x["epsilon"])]
        add("### 9.2 Differential privacy (DP-SGD with Opacus)", "", *_img(figs, "dp", "Privacy / utility"),
            md_table(["Privacy budget per client", "Mean noise multiplier", "F1", "PR-AUC"], rows), "",
            f"Example-level (ε, δ = {d['private'][0]['delta']:g})-DP for each client's own training rows, clipping norm {d['private'][0]['max_grad_norm']:g}, "
            "accounted with Rényi DP over all local steps of the run. Smaller clients need more noise for the same budget. The clipping norm was chosen on "
            "validation at ε = 3 on one seed (12 combinations of clipping norm, batch size and learning rate); an untuned setting was clearly worse.", "")
        write_csv(tables_dir / "privacy_utility.csv", ["budget", "noise_multiplier", "f1", "pr_auc"], rows)
    if st["poison"]:
        p = st["poison"]
        labels = {"no_attack": "No attack", "attack_no_defence": "Attack, no defence", "attack_median_clipping": "Attack, median norm clipping",
                  "no_attack_median_clipping": "No attack, median norm clipping"}
        rows = [[labels[k], pm([r.get("last_round_f1", r["f1"]) for r in runs]), pm([r["f1"] for r in runs]), f"{np.mean([r['best_round'] for r in runs]):.0f}"]
                for k, runs in p["runs"].items()]
        a = p["attack"]
        add("### 9.3 Model poisoning and norm clipping", "", *_img(figs, "poison", "Poisoning"),
            md_table(["Condition", "F1, model of the last round", "F1, round selected on validation", "Selected round"], rows), "",
            f"Attack: client {a['clients']} of {primary_scenario(cfg).n_clients} sends its update {'sign-flipped and ' if a['mode'] == 'signflip' else ''}scaled by {a['scale']:g} in every round. "
            "Without a defence training diverges; selecting the round on validation only rolls back to an early model, it does not repair anything. "
            "Clipping every update to the round's median norm keeps training alive at a cost, with or without an attacker, because it also shrinks the "
            "largest honest client's update. It does not stop a patient attacker whose updates stay within the bound (a backdoor).", "")
